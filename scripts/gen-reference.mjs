// Generates the ballistics reference fixture and the G7 drag table.
//
//   npm run gen:reference
//
// Outputs:
//   tests/fixtures/reference.json   - js-ballistics trajectories used to validate the in-game solver
//   src/ballistics/g7.ts            - G7 drag table copied from js-ballistics (ISC license)
//
// js-ballistics is a devDependency; it is used by this script only and is never imported by src/.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  Ammo,
  Atmo,
  Calculator,
  Distance,
  DragModel,
  DragTables,
  Shot,
  UNew,
  Velocity,
  Weapon,
  Wind,
} from 'js-ballistics';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Rifle data (spec 5.5). Diameters in inches, weights in grains.
const RIFLES = {
  308: { bc: 0.243, grains: 175, inches: 0.308, mv: 790 },
  338: { bc: 0.322, grains: 250, inches: 0.338, mv: 900 },
};

const AIR = {
  standard: () => Atmo.standard(),
  desert: () =>
    new Atmo({
      altitude: UNew.Meter(0),
      temperature: UNew.Celsius(38),
      pressure: UNew.hPa(1013.25),
      humidity: 0,
    }),
};

// 10 mph = 4.4704 m/s
const WINDS_MPS = [0, 4.4704];

const RANGE_M = 1500;
const STEP_M = 100;

async function runCase(rifleKey, airKey, windFromLeftMps) {
  const { bc, grains, inches, mv } = RIFLES[rifleKey];
  const atmo = AIR[airKey]();
  const shot = new Shot({
    weapon: new Weapon({ sightHeight: UNew.Centimeter(4) }),
    ammo: new Ammo({
      dm: new DragModel({ bc, dragTable: DragTables.G7, weight: grains, diameter: inches }),
      mv: UNew.MPS(mv),
    }),
    atmo,
    // directionFrom 90 deg = wind from the shooter's left, pushing right (+windage).
    winds: [new Wind({ velocity: UNew.MPS(windFromLeftMps), directionFrom: UNew.Degree(90) })],
  });

  const calc = new Calculator();
  await calc.setWeaponZero(shot, UNew.Meter(100));
  const hit = await calc.fire({
    shot,
    trajectoryRange: UNew.Meter(RANGE_M),
    trajectoryStep: UNew.Meter(STEP_M),
  });

  const samples = hit.samples
    .map((p) => ({
      range: p.distance.In(Distance.Meter),
      time: p.time,
      height: p.height.In(Distance.Meter),
      windage: p.windage.In(Distance.Meter),
      velocity: p.velocity.In(Velocity.MPS),
      mach: p.mach,
      densityRatio: p.densityRatio,
    }))
    // drop the 0 m sample
    .filter((s) => s.range > 0.5)
    .map((s) => ({ ...s, range: Math.round(s.range) }));

  const expectedSamples = RANGE_M / STEP_M;
  if (samples.length !== expectedSamples) {
    throw new Error(`${rifleKey}/${airKey}/${windFromLeftMps}: expected ${expectedSamples} samples, got ${samples.length}`);
  }
  samples.forEach((s, i) => {
    if (s.range !== (i + 1) * STEP_M) {
      throw new Error(`${rifleKey}/${airKey}/${windFromLeftMps}: unexpected range ${s.range} at index ${i}`);
    }
  });

  return { rifle: rifleKey, air: airKey, windFromLeftMps, samples };
}

async function writeReference() {
  const cases = [];
  for (const rifleKey of Object.keys(RIFLES)) {
    for (const airKey of Object.keys(AIR)) {
      for (const windFromLeftMps of WINDS_MPS) {
        cases.push(await runCase(rifleKey, airKey, windFromLeftMps));
      }
    }
  }
  const out = resolve(root, 'tests/fixtures/reference.json');
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, JSON.stringify({ cases }, null, 2) + '\n');
  console.log(`wrote ${out} (${cases.length} cases)`);
}

async function writeG7Table() {
  const rows = DragTables.G7.map(({ Mach, CD }) => `  { mach: ${Mach}, cd: ${CD} },`).join('\n');
  const src = `// G7 standard drag table (Mach -> Cd).
// Generated by scripts/gen-reference.mjs from DragTables.G7 in js-ballistics
// (https://github.com/o-murphy/js-ballistics), ISC License, Copyright 2023 o-murphy.
// Do not edit by hand; run \`npm run gen:reference\`.

export const G7_TABLE: ReadonlyArray<{ mach: number; cd: number }> = [
${rows}
];
`;
  const out = resolve(root, 'src/ballistics/g7.ts');
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, src);
  console.log(`wrote ${out} (${DragTables.G7.length} rows)`);
}

await writeReference();
await writeG7Table();
